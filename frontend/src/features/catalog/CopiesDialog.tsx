import { useState } from "react";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { Plus, Trash2, Copy, BookOpen, Pencil, Check, X } from "lucide-react";
import { apiFetch } from "../../lib/api";
import { phDate, phISODate } from "../../lib/dates";
import { useAuth } from "../auth/auth";
import { useToast } from "../../components/Toast";
import { Badge, Skeleton, StaffDialog, btn, btnSm, table, type badgeTone, select, input } from "../../components/staff/ui";
import type { Book } from "./Catalog";
import { queuedToast } from "../../lib/offline";

interface CopyRow { id: string; barcode: string; status: string; lastVerifiedAt?: string | null; location?: string | null; acquiredAt?: string | null }
const STATUS_TONE: Record<string, keyof typeof badgeTone> = { AVAILABLE: "success", BORROWED: "primary", LOST: "danger", DAMAGED: "warning", RETIRED: "muted" };

/** Status changes the server allows (BORROWED only changes through circulation). */
export const allowedTransitions = (status: string) => {
  if (status === "AVAILABLE" || status === "BORROWED") return ["LOST", "DAMAGED", "RETIRED"];
  if (status === "LOST" || status === "DAMAGED") return ["AVAILABLE", "RETIRED"];
  return [];
};

/** Physical copies of one book (opened from the Catalog row). */
export function CopiesDialog({ book, onClose }: { book: Book | null; onClose: () => void }) {
  const { token, hasPerm } = useAuth();
  const toast = useToast();
  const qc = useQueryClient();
  const canWrite = hasPerm("copies:write");
  const [confirm, setConfirm] = useState<string | null>(null);
  // Copy being edited: its shelf location and date received.
  const [edit, setEdit] = useState<{ id: string; location: string; dateReceived: string } | null>(null);

  const list = useQuery({
    queryKey: ["copies", book?.id],
    queryFn: async () => { const r = await apiFetch(`/api/v1/book-copies?bookId=${book!.id}&limit=100`, { token }); if (!r.ok) throw new Error(r.message); return r.data as { items: CopyRow[]; total: number }; },
    enabled: !!token && !!book,
  });
  const refresh = () => ["copies", "copies-summary", "catalog", "summary"].forEach(k => qc.invalidateQueries({ queryKey: [k] }));
  const call = async (path: string, method: string, body?: object, offline?: Parameters<typeof apiFetch>[1] extends infer I ? I extends { offline?: infer O } ? O : never : never) => {
    const r = await apiFetch(path, { method, token, ...(body ? { body: JSON.stringify(body) } : {}), ...(offline ? { offline } : {}) });
    if (!r.ok) throw new Error(r.status === 0 ? "No internet. This needs a connection." : r.message ?? "Request failed");
    return r;
  };
  const fail = (title: string) => (e: Error) => toast({ tone: "error", title, message: e.message });

  // Staff identify copies by the book's ISBN plus a copy number; the internal copy code is generated by the server.
  const isbn = book?.isbn || "N/A";
  const nameOf = (c: CopyRow) => `Copy ${(list.data?.items.findIndex(x => x.id === c.id) ?? -1) + 1}`;
  const add = useMutation({
    mutationFn: () => call("/api/v1/book-copies", "POST", { bookId: book!.id }, { kind: "copy", label: `Add a copy of "${book!.title}" (ISBN ${isbn})` }),
    onSuccess: (r) => { toast(r.queued ? queuedToast : { tone: "success", title: "Copy added", message: `A new copy of "${book!.title}" (ISBN ${isbn}) is on the shelf.` }); refresh(); },
    onError: fail("Could not add copy"),
  });
  const setStatus = useMutation({
    mutationFn: ({ c, status }: { c: CopyRow; status: string }) => call(`/api/v1/book-copies/${c.id}/status`, "PATCH", { status }).then(() => ({ c, status })),
    onSuccess: ({ c, status }) => { toast({ tone: "success", title: "Status updated", message: `${nameOf(c)} is now ${status.toLowerCase()}.` }); refresh(); },
    onError: fail("Could not update status"),
  });
  const saveDetails = useMutation({
    mutationFn: (e: { id: string; location: string; dateReceived: string }) => call(`/api/v1/book-copies/${e.id}`, "PATCH", { location: e.location, dateReceived: e.dateReceived }),
    onSuccess: () => { toast({ tone: "success", title: "Copy updated", message: "Location and date received were saved." }); setEdit(null); refresh(); },
    onError: fail("Could not save the copy"),
  });
  const remove = useMutation({
    mutationFn: (c: CopyRow) => call(`/api/v1/book-copies/${c.id}`, "DELETE").then(() => c),
    onSuccess: (c) => { toast({ tone: "success", title: "Copy removed", message: `${nameOf(c)} of "${book!.title}" was removed.` }); setConfirm(null); refresh(); },
    onError: fail("Could not remove copy"),
  });

  return (
    <StaffDialog open={!!book} onClose={() => { setConfirm(null); onClose(); }} title={book ? book.title : "Book copies"} subtitle={`ISBN ${isbn}${list.data ? ` · ${list.data.total} physical cop${list.data.total === 1 ? "y" : "ies"}` : ""}`} icon={Copy} wide>
      <div className="flex flex-wrap items-center gap-3 p-4 rounded-2xl border border-line bg-page/60">
        <span className="w-11 h-11 rounded-xl bg-primary-soft text-primary flex items-center justify-center shrink-0" aria-hidden="true"><BookOpen size={20} /></span>
        <div className="flex-1 min-w-40">
          <p className="text-xs font-semibold uppercase tracking-wide text-ink-muted">ISBN</p>
          <p className="font-mono font-semibold text-ink">{isbn}</p>
        </div>
        {canWrite && <button type="button" onClick={() => add.mutate()} className={btn.success} disabled={add.isPending}><Plus size={16} aria-hidden="true" />{add.isPending ? "Adding…" : "Add a copy"}</button>}
      </div>

      {list.isLoading ? <Skeleton rows={3} className="h-12" /> : list.isError ? <p role="alert" className="text-danger text-sm">Could not load copies.</p> : !list.data?.items.length ? (
        <p className="text-center text-ink-muted py-6">No copies yet.{canWrite ? " Press Add a copy." : ""}</p>
      ) : (
        <div className={table.wrap}>
          <table className={table.table}>
            <thead className={table.head}><tr><th className={table.th}>Copy</th><th className={table.th}>Location · Received</th><th className={table.th}>Status</th><th className={table.th}>Change status</th><th className={`${table.th} text-right`}>Actions</th></tr></thead>
            <tbody>
              {list.data.items.map(c => (
                <tr key={c.id} className={table.row}>
                  <td className={`${table.td} font-semibold text-ink whitespace-nowrap`}>{nameOf(c)}</td>
                  <td className={`${table.td} min-w-[12rem]`}>
                    {edit?.id === c.id ? (
                      <div className="grid grid-cols-[1fr_auto_auto] items-center gap-2">
                        <label className="sr-only" htmlFor={`loc-${c.id}`}>Location</label>
                        <input id={`loc-${c.id}`} value={edit.location} maxLength={100} placeholder="e.g. Shelf A3" onChange={e => setEdit({ ...edit, location: e.target.value })} className={`${input} !min-h-9 !py-1 col-span-3`} />
                        <label className="sr-only" htmlFor={`rcv-${c.id}`}>Date received</label>
                        <input id={`rcv-${c.id}`} type="date" value={edit.dateReceived} onChange={e => setEdit({ ...edit, dateReceived: e.target.value })} className={`${input} !min-h-9 !py-1 !px-2 text-sm min-w-0`} />
                        <button type="button" aria-label="Save" disabled={saveDetails.isPending} onClick={() => saveDetails.mutate(edit)} className={`${btn.primary} ${btnSm}`}><Check size={14} aria-hidden="true" /></button>
                        <button type="button" aria-label="Cancel" onClick={() => setEdit(null)} className={`${btn.ghost} ${btnSm}`}><X size={14} aria-hidden="true" /></button>
                      </div>
                    ) : (
                      <div className="flex items-center gap-2">
                        <div className="text-xs"><div className="text-ink font-medium">{c.location || <span className="text-ink-muted italic">No location</span>}</div><div className="text-ink-muted">{c.acquiredAt ? `Received ${phDate(c.acquiredAt)}` : "Date received not set"}</div></div>
                        {canWrite && <button type="button" aria-label={`Edit location and date received of ${nameOf(c)}`} onClick={() => setEdit({ id: c.id, location: c.location ?? "", dateReceived: c.acquiredAt ? phISODate(c.acquiredAt) : "" })} className={`${btn.ghost} ${btnSm}`}><Pencil size={14} aria-hidden="true" /></button>}
                      </div>
                    )}
                  </td>
                  <td className={table.td}><Badge tone={STATUS_TONE[c.status] ?? "muted"}>{c.status}</Badge><div className="text-[11px] text-ink-muted mt-1">{c.lastVerifiedAt ? `Verified ${phDate(c.lastVerifiedAt)}` : "Not verified"}</div></td>
                  <td className={table.td}>
                    <select aria-label={`Status of ${nameOf(c)}`} className={`${select} !min-h-9 !py-1 !rounded-xl min-w-[8.5rem]`} value={c.status} disabled={!canWrite || allowedTransitions(c.status).length === 0 || setStatus.isPending} onChange={e => setStatus.mutate({ c, status: e.target.value })}>
                      <option value={c.status}>{c.status}</option>
                      {allowedTransitions(c.status).map(st => <option key={st} value={st}>{st}</option>)}
                    </select>
                  </td>
                  <td className={`${table.td} text-right`}>
                    {canWrite && (confirm === c.id ? (
                      <span className="inline-flex gap-2 ak-fade">
                        <button className={`${btn.danger} ${btnSm}`} disabled={remove.isPending} onClick={() => remove.mutate(c)}>Remove</button>
                        <button className={`${btn.ghost} ${btnSm}`} onClick={() => setConfirm(null)}>Cancel</button>
                      </span>
                    ) : (
                      <button className={`${btn.secondary} ${btnSm} !text-danger hover:!border-danger hover:!bg-danger-soft`} onClick={() => setConfirm(c.id)} aria-label={`Remove ${nameOf(c)}`}><Trash2 size={14} aria-hidden="true" /></button>
                    ))}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </StaffDialog>
  );
}
